/**
 * 전체 시군구 평탄 목록 — 탐색 쿼리 `district` 의 `@IsIn` 검증용.
 *
 * 시/도별로 검증하지 않고 평탄 집합으로 1차 검증한 뒤, 시/도와의 조합 정합은
 * `isValidDistrict()` 로 확인한다. 시군구 이름은 시/도 간 중복이 많아
 * ("중구"·"동구"·"서구"·"고성군" 등) 평탄 집합만으로는 조합을 보증할 수 없다.
 */
export const ALL_DISTRICTS: readonly string[] = Array.from(
  new Set(Object.values(CITY_DISTRICTS).flat()),
);

/** 시/도 값이 SoT 목록에 있는지 */
export function isVenueCity(value: unknown): value is VenueCity {
  return (
    typeof value === "string" &&
    (VENUE_CITIES as readonly string[]).includes(value)
  );
}

/**
 * 시/도 + 시군구 조합 정합 검증.
 * 도시가 유효하지 않거나 그 도시에 없는 시군구면 false — "부산 강남구" 같은
 * 조합을 막는다(평탄 목록만 보면 통과해버린다).
 */
export function isValidDistrict(city: unknown, district: unknown): boolean {
  if (!isVenueCity(city)) return false;
  return (
    typeof district === "string" && CITY_DISTRICTS[city].includes(district)
  );
}
